/**
 * Power: DOCUMENT
 * Architecture documentation generation.
 * Creates structured docs, diagrams, and reports.
 *
 * When to use: The user wants architecture documentation,
 *   design reports, or system overview documents.
 */

const fs = require('fs');
const path = require('path');

class PowerDocument {
  constructor(options = {}) {
    this.outputDir = options.outputDir || path.join(process.cwd(), 'output', 'documents');
    this.ensureDir();
  }

  ensureDir() {
    if (!fs.existsSync(this.outputDir)) {
      fs.mkdirSync(this.outputDir, { recursive: true });
    }
  }

  status() {
    return {
      ready: true,
      outputDir: this.outputDir
    };
  }

  execute(mission) {
    const action = mission.action || 'generate';

    try {
      switch (action) {
        case 'generate': {
          const title = mission.title || 'Architecture Document';
          const content = this.generateDoc(title, mission);
          const fileName = (mission.fileName || title.replace(/\s+/g, '-').toLowerCase()) + '.md';
          const filePath = path.join(this.outputDir, fileName);
          fs.writeFileSync(filePath, content, 'utf8');
          return {
            output: {
              generated: true,
              title,
              filePath,
              size: content.length
            }
          };
        }
        case 'report': {
          const report = this.generateReport(mission.data || {});
          const filePath = path.join(this.outputDir, 'report-' + Date.now() + '.md');
          fs.writeFileSync(filePath, report, 'utf8');
          return {
            output: {
              generated: true,
              filePath,
              size: report.length
            }
          };
        }
        case 'export-html': {
          const source = mission.source || '';
          const html = this.toHtml(source);
          const filePath = path.join(this.outputDir, (mission.name || 'export') + '.html');
          fs.writeFileSync(filePath, html, 'utf8');
          return {
            output: {
              exported: true,
              filePath,
              size: html.length
            }
          };
        }
        default:
          return {
            error: `Unknown document action: ${action}. Available: generate, report, export-html`
          };
      }
    } catch (error) {
      return {
        error: error.message,
        stack: error.stack
      };
    }
  }

  generateDoc(title, mission) {
    const sections = mission.sections || ['Overview', 'Architecture', 'Components', 'Next Steps'];
    const lines = [`# ${title}`, '', `*Generated by Soul Architect on ${new Date().toISOString()}*`, ''];
    sections.forEach(section => {
      lines.push(`## ${section}`, '');
      if (mission.content && mission.content[section]) {
        lines.push(mission.content[section], '');
      } else {
        lines.push(`(Content for ${section} to be added.)`, '');
      }
    });
    return lines.join('\n');
  }

  generateReport(data) {
    const lines = [
      '# Architecture Report',
      '',
      `Date: ${new Date().toISOString()}`,
      '',
      '## Summary',
      '',
      JSON.stringify(data, null, 2),
      '',
      '## Recommendations',
      '',
      '- Review generated architecture against requirements',
      '- Validate pattern choices with team',
      '- Add observability and monitoring',
      ''
    ];
    return lines.join('\n');
  }

  toHtml(source) {
    const escaped = source
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;');
    return `<!DOCTYPE html><html><head><title>Architect Export</title></head><body><pre>${escaped}</pre></body></html>`;
  }
}

module.exports = PowerDocument;
